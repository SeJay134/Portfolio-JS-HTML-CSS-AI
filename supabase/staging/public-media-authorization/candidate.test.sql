begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select no_plan();
select ok(exists(select 1 from pg_roles where rolname='studio_public_media_reader' and not rolcanlogin and not rolbypassrls and not rolsuper and not rolcreaterole),'reader non-login non-bypass');
select ok(not pg_has_role('anon','studio_public_media_reader','MEMBER'),'anon cannot assume reader');
select ok(not pg_has_role('authenticated','studio_public_media_reader','MEMBER'),'browser cannot assume reader');
select ok(not pg_has_role('studio_public_media_reader','service_role','MEMBER'),'reader cannot assume service role');
select ok(not has_table_privilege('studio_public_media_reader','private.studio_media_assets','SELECT'),'reader no direct metadata read');
select ok(not has_table_privilege('studio_public_media_reader','storage.objects','INSERT'),'reader cannot upload');
select ok(not has_table_privilege('studio_public_media_reader','storage.objects','UPDATE'),'reader cannot overwrite');
select ok(not has_table_privilege('studio_public_media_reader','storage.objects','DELETE'),'reader cannot delete');
select ok(not has_function_privilege('anon','public.resolve_public_media(uuid)','EXECUTE'),'anon resolver denied');
select ok(not has_function_privilege('authenticated','public.resolve_public_media(uuid)','EXECUTE'),'browser resolver denied');
select ok(not has_function_privilege('studio_public_media_reader','public.change_studio_publication(uuid,integer,integer,uuid,text)','EXECUTE'),'reader cannot publish');
select ok(not has_function_privilege('studio_public_media_reader','public.save_studio_draft(uuid,integer,uuid,jsonb)','EXECUTE'),'reader cannot save');
select ok(not (select prosecdef from pg_proc where oid='public.resolve_public_media(uuid)'::regprocedure),'public resolver invoker');
select * from finish();
rollback;
