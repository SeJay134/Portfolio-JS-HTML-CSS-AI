import React from "react";
import { act, fireEvent, render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import { BlogStudioWorkspace } from "../../../src/components/BlogStudioWorkspace";
import { RequireBlogAdmin } from "../../../src/auth/RequireBlogAdmin";
const mocks = vi.hoisted(() => ({ auth: vi.fn(), resolve: vi.fn(), enabled: vi.fn() }));
vi.mock("../../../src/auth/AuthProvider", () => ({ useAuth: mocks.auth }));
vi.mock("../../../src/auth/blogAdmin", () => ({ resolveBlogAdmin: mocks.resolve, isBlogAdminEnabled: mocks.enabled }));
vi.mock("../../../src/auth/GoogleLoginButton", () => ({ GoogleLoginButton: () => <button>Continue with Google</button> }));
beforeEach(() => {
  mocks.enabled.mockReturnValue(true);
  mocks.auth.mockReturnValue({ status: "authenticated", authRevision: 0, user: { id: "owner" }, signOut: vi.fn() });
  mocks.resolve.mockReset().mockResolvedValue(true);
});
it("composes, formats, reorders and previews escaped text with inert links", async () => {
  const user = userEvent.setup();
  render(<BlogStudioWorkspace />);
  await user.click(screen.getByRole("button", { name: "+ New draft" }));
  fireEvent.change(screen.getByLabelText("Article title"), { target: { value: "Fixture article" } });
  fireEvent.change(screen.getByLabelText("Block 1 text part 1", { exact: true }), { target: { value: "<script>alert(1)</script>" } });
  await user.click(screen.getByRole("button", { name: "Block 1 text part 1 bold" }));
  await user.click(screen.getByRole("button", { name: "Block 1 text part 1 italic" }));
  fireEvent.change(screen.getByLabelText("Link for block 1 text part 1 (optional)"), { target: { value: "https://example.com" } });
  await user.selectOptions(screen.getByLabelText("Block type"), "heading");
  await user.click(screen.getByRole("button", { name: "+ Add block" }));
  fireEvent.change(screen.getByLabelText("Block 2 content"), { target: { value: "Introduction" } });
  await user.click(screen.getByRole("button", { name: "Block 2 move up" }));
  await user.click(screen.getByRole("button", { name: "Preview" }));
  const preview = within(screen.getByRole("article"));
  expect(preview.getByRole("heading", { name: "Fixture article" })).toBeVisible();
  expect(preview.getByRole("heading", { name: "Introduction" })).toBeVisible();
  const escaped = preview.getByText("<script>alert(1)</script>");
  expect(escaped.closest("strong")).not.toBeNull();
  expect(escaped.closest("em")).not.toBeNull();
  expect(escaped.closest("a")).toBeNull();
  expect(document.querySelector(".studio-preview script")).toBeNull();
  expect(screen.queryByRole("button", { name: /publish/i })).not.toBeInTheDocument();
});
it("supports multiple temporary drafts, search, discard and validation", async () => {
  const user = userEvent.setup();
  vi.spyOn(window, "confirm").mockReturnValue(true);
  render(<BlogStudioWorkspace />);
  await user.click(screen.getByRole("button", { name: "+ New draft" }));
  fireEvent.change(screen.getByLabelText("Article title"), { target: { value: "First draft" } });
  await user.click(screen.getByRole("button", { name: "+ New draft" }));
  fireEvent.change(screen.getByLabelText("Article title"), { target: { value: "Second draft" } });
  fireEvent.change(screen.getByLabelText("Search drafts"), { target: { value: "First" } });
  const library = within(screen.getByRole("complementary", { name: "Draft library" }));
  expect(library.queryByRole("button", { name: /Second draft/ })).not.toBeInTheDocument();
  await user.click(library.getByRole("button", { name: /First draft/ }));
  expect(screen.getByLabelText("Article title")).toHaveValue("First draft");
  fireEvent.change(screen.getByLabelText("Link for block 1 text part 1 (optional)"), { target: { value: "javascript:alert(1)" } });
  await user.click(screen.getByRole("button", { name: "Preview" }));
  expect(screen.getByRole("alert")).toHaveTextContent("Use an http/https");
  await user.click(screen.getByRole("button", { name: "Discard draft" }));
  expect(screen.getByLabelText("Article title")).toHaveValue("Second draft");
});
it("unmounts private workspace and discards draft after access loss", async () => {
  const view = render(<RequireBlogAdmin><BlogStudioWorkspace /></RequireBlogAdmin>);
  const user = userEvent.setup();
  await user.click(await screen.findByRole("button", { name: "+ New draft" }));
  fireEvent.change(screen.getByLabelText("Article title"), { target: { value: "Private temporary text" } });
  mocks.resolve.mockResolvedValue(false);
  await act(async () => { window.dispatchEvent(new Event("focus")); });
  expect(await screen.findByRole("alert")).toHaveTextContent("Administrator access is not available");
  expect(screen.queryByLabelText("Article title")).not.toBeInTheDocument();
  mocks.resolve.mockResolvedValue(true);
  await user.click(screen.getByRole("button", { name: "Retry access check" }));
  expect(await screen.findByText("No local drafts")).toBeVisible();
  expect(screen.queryByText("Private temporary text")).not.toBeInTheDocument();
  view.unmount();
});
